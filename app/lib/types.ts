/**
 * Format unit into Bengali label
 */
export function formatUnitBn(unit: string): string {
  switch (unit.toLowerCase()) {
    case "kg":
      return "প্রতি কেজি";
    case "litre":
    case "liter":
      return "প্রতি লিটার";
    case "dozen":
      return "প্রতি ডজন";
    case "piece":
    case "pc":
      return "প্রতি পিস";
    default:
      return `প্রতি ${unit}`;
  }
}
